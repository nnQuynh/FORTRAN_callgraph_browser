************************************************************************
*                                                                      *
      subroutine usrelst1(icnt,icels,ioel,erg,outdd,sigtt)
*                                                                      *
*        sample subroutine for user defined elastic option             *
*                                                                      *
*        input :                                                       *
*           icnt  : =1 total x section, =2 coherent elastic costh,     *
*                   =3 capture, =4 cohe. incohe. elastic or inelastic  *
*           icels : =0 this els, =1 back to normal elastic             *
*           ioel  : region id                                          *
*           erg   : neutron energy in MeV                              *
*                                                                      *
*        output :                                                      *
*           outdd : icnt=2, cos(the) of outgoing angle in CM system    *
*           outdd : icnt=3, capture cross section                      *
*           outdd : icnt=4, -1 elastic cohe. 1 elastic incoh.          *
*                           11 inleastic                               *
*           sigtt : total cross section (barn)                         *
*                                                                      *
*                                                                      *
************************************************************************

      implicit real*8 (a-h,o-z)

*-----------------------------------------------------------------------

      include 'param.inc'

      parameter ( pi  = 3.1415926535898d0 )

*-----------------------------------------------------------------------

      common /verjam/ versn, lastr, iyeav, imonv, idayv
      common /elreg/  elarg(kvlmax,4), mlrgn, melrg(kvlmax,2), ielusr
      common /regdc/  idrg(kvlmax), idgr(kvmmax)
      common /paraj/ mstz(300), parz(300)

*-----------------------------------------------------------------------

      data ifst1 /0/
      data ifst2 /0/
      save ifst1,ifst2 !FURUTA
!$OMP THREADPRIVATE(ifst1,ifst2)
*-----------------------------------------------------------------------
*              c1: maximum energy for data base (eV)
*              c2: material id
*                  =1 ; Al
*                  =2 ; Fe
*-----------------------------------------------------------------------

               c1 = elarg(ioel,1)
               c2 = elarg(ioel,2)
               c3 = elarg(ioel,3)
               c4 = elarg(ioel,4)

*-----------------------------------------------------------------------
*     back to normal elastic angular distribution icels =1
*-----------------------------------------------------------------------

            icels = 0

         if( erg .gt. c1 * 1.e-6 ) then

            icels = 1
            return

         end if

           rlam = 2.86e-1 / sqrt( erg * 1.e+6 )   ! A

*-----------------------------------------------------------------------
*     total cross section by user's data
*-----------------------------------------------------------------------

      if( icnt .eq. 1 ) then

         if( nint(c2) .eq. 1 ) then

            call altot1(icnt,rlam,sigtt,sigca,sigec,sigei,sigin,icels)

         else if( nint(c2) .eq. 2 ) then

            call fetot1(icnt,rlam,sigtt,sigca,sigec,sigei,sigin,icels)

         end if

*-----------------------------------------------------------------------
*     capture cross section by user's data
*-----------------------------------------------------------------------

      else if( icnt .eq. 3 ) then

         if( nint(c2) .eq. 1 ) then

            call altot1(icnt,rlam,sigtt,sigca,sigec,sigei,sigin,icels)

         else if( nint(c2) .eq. 2 ) then

            call fetot1(icnt,rlam,sigtt,sigca,sigec,sigei,sigin,icels)

         end if

            outdd = sigca

*-----------------------------------------------------------------------
*     elastic or inelastic cross section by user's data
*-----------------------------------------------------------------------

      else if( icnt .eq. 4 ) then

         if( nint(c2) .eq. 1 ) then

            call altot1(icnt,rlam,sigtt,sigca,sigec,sigei,sigin,icels)

         else if( nint(c2) .eq. 2 ) then

            call fetot1(icnt,rlam,sigtt,sigca,sigec,sigei,sigin,icels)

         end if

            brnc = sigec + sigei + sigin
            rcho = rang() * brnc

         if( rcho .le. sigec ) then

            outdd = -1.d0

         else if( rcho .le. sigec + sigei ) then

            outdd =  1.d0

         else

            outdd = 11.d0
            sigtt = rcho - sigec - sigei

         end if

*-----------------------------------------------------------------------
*     coherent elastic : determine cos from data base
*-----------------------------------------------------------------------

      else if( icnt .eq. 2 ) then

         if( nint(c2) .eq. 1 ) then

            if( ifst1 .eq. 0 ) then

               call alint

               ifst1 = 1

            end if

               call alcos(rlam,costh,icels)

         else if( nint(c2) .eq. 2 ) then

            if( ifst2 .eq. 0 ) then

               call feint

               ifst2 = 1

            end if

               call fecos(rlam,costh,icels)

         end if

               outdd = costh

      end if

*-----------------------------------------------------------------------

      return
      end

************************************************************************
*                                                                      *
      subroutine alcos(rlam,costh,icels)
*                                                                      *
*        for Al based on the data base                                 *
*                                                                      *
*        input :                                                       *
*           rlam : lambda (A)                                          *
*                                                                      *
*        output :                                                      *
*           costh : cos(theta) scattering angle                        *
*           icels : =0 this els, =1 back to normal elastic             *
*                                                                      *
*                                                                      *
************************************************************************

      implicit real*8 (a-h,o-z)

*-----------------------------------------------------------------------

      common /scatal/ fal(227), dal(227), ual(227), idal

      dimension       stng(1000), prob(1000), dist(1000)
      save            stng, prob, dist, idn, allp
!$OMP THREADPRIVATE(stng, prob, dist, idn, allp)
      data pinc / 0.006d0 /

*-----------------------------------------------------------------------
*        incoherent scattering
*-----------------------------------------------------------------------

            icels = 0

*-----------------------------------------------------------------------

               sek = 0.d0

         do i = 1, idn

               sinth = rlam / 2.d0 / dist(i)

            if( sinth .gt. 1.d0 ) then

               ids = i - 1
               goto 200

            end if

               sek = sek + stng(i)

         end do

              ids = idn

  200    continue

         if( ids .eq. 0 ) then

            icels = 1
            return

         end if

*-----------------------------------------------------------------------

            sek = 0.d0

         do i = 1, ids

            sinth = rlam / 2.d0 / dist(i)
            cos2t = 1.d0 - 2.d0 * sinth**2
            sin2t = sqrt( 1.d0 - cos2t**2 )

            prob(i) = stng(i) * sin2t
            sek = sek + prob(i)

         end do

            seb = 0.d0

         do i = 1, ids

            prob(i) = prob(i) / sek
            seb = seb + prob(i)
            prob(i) = seb

         end do


*-----------------------------------------------------------------------

            rn = unirn(dummy)

         do i = 1, ids

            if( rn .le. prob(i) ) then

               id = i
               goto 100

            end if

         end do

            icels = 1
            return

  100    continue

            sinth = rlam / 2.d0 / dist(id)
            costh = 1.d0 - 2.d0 * sinth**2

      return

************************************************************************
*                                                                      *
      entry alint
*                                                                      *
*        for Al, initialization of the data base                       *
*                                                                      *
************************************************************************

*-----------------------------------------------------------------------

            idn = idal

         do i = 1, idn

            dist(i) = dal(i)
            stng(i) = fal(i)**2 * ual(i)

         end do

            sek = 0.d0

         do i = 1, idn

            sek = sek + stng(i)

         end do

            allp = sek

*-----------------------------------------------------------------------

      return
      end

************************************************************************
