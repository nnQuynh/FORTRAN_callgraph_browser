      subroutine fastdr(iu,aa,n)
*                                                                      *
*       read or write length n array to sequential unformatted unit iu *
*       arrays:   aa=64-bit float; bb=32-bit float; jj=integer.        *
*       the purpose is to speed up certain i/o operations:  in some    *
