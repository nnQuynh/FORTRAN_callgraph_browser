      subroutine nxtsym(hs,hd,ir,it,iu,ic)
*                                                                      *
*       find the next symbol in hs, starting at position ir.  the      *
*       found symbol starts at position it and ends at position iu.    *
*       iu=0 means no symbol was found, including ir > length of hs.   *
*       hd contains the delimiters.  delimiters other than blanks are  *
*       themselves symbols.  If ic=0 the case is not changed; if ic=1  *
*       the next symbol is reduced to lowercase; and if ic=2 a symbol  *
*       is not searched for and the entire hs string becomes lowercase *
*                                                                      *
*       Last modified by K.Niita on 2009/09/28                         *
*                                                                      *
************************************************************************

      implicit real*8 (a-h,o-z)

*-----------------------------------------------------------------------

      character hs*(*),hd*(*),hu*26,hl*26

*     hu alphabet must be upper case.

      data hu /'ABCDEFGHIJKLMNOPQRSTUVWXYZ'/,
     &     hl /'abcdefghijklmnopqrstuvwxyz'/

*-----------------------------------------------------------------------

         iu = 0
         it = ir
         l = len(hs)
         if(ic.eq.2) goto 50
         if(ir.gt.l) return
         if(index(hd,' ').eq.0) goto 20

      do 10 it = ir, l
   10    if(hs(it:it).ne.' ') goto 20
         return

   20 do 30 iu = it, l
   30    if(index(hd,hs(iu:iu)).ne.0) goto 40

   40    iu = max(it,iu-1)
         goto (80,60,50) ic + 1

   50    it = 1
         iu = l

   60 do 70 i = it, iu
         j = index(hu,hs(i:i))
   70    if(j.ne.0) hs(i:i) = hl(j:j)

   80 return
      end

