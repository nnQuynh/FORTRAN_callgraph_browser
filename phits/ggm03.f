*                                                                      *
      function screen(ar)
*                                                                      *
*       calculate the screening factor for the thomas-fermi model.     *
*       Last modified by K.Niita on 2009/09/30                         *
*                                                                      *
************************************************************************

      implicit double precision (a-h,o-z)

*-----------------------------------------------------------------------
      dimension a(3),b(3)
      data a/.1,.55,.35/,b/1.,.2,.05/

*-----------------------------------------------------------------------

         screen = 0.

      do 40 i = 1, 3
      do 40 j = 1, 3

         s = (ar*b(j))**2
         if(s.gt..1) goto 20
         tl = 0.
         t = -1.

      do 10 n= 1, 9
         if(abs(t).lt.n*1e-9) goto 30
         t = -t*s
   10    tl = tl+t/n

         goto 30

   20    tl = log(1.+s)
   30    if(i.eq.j) screen = screen-.5*tl*a(i)**2
   40    if(i.ne.j) screen = screen
     &                     + a(i)*a(j)*((1.+s)*tl/((ar*b(i))**2-s)+.5)

*-----------------------------------------------------------------------

      return
      end

