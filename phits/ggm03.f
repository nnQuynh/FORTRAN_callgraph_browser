      function qpol(s,x,y,n)
*                                                                      *
*       interpolate quadratically in tabular function y(x), whose      *
*       length is n, to get qpol, which is the value of y at x=s.      *
*       Last modified by K.Niita on 2009/09/28                         *
*                                                                      *
************************************************************************

      implicit real*8 (a-h,o-z)

*-----------------------------------------------------------------------

      dimension x(n),y(n)

*-----------------------------------------------------------------------

         if(n.eq.2) goto 80
         i = 1
         if(x(1).gt.x(n)) goto 30
         if(s.le.x(2)) goto 70
         if(s.ge.x(n-1)) goto 60

      do 10 i = 2, n-2
   10    if(s.lt.x(i+1)) goto 20

   20    if(s.le..5*(x(i-1)+x(i+2))) i = i - 1
         goto 70

   30    if(s.ge.x(2)) goto 70
         if(s.le.x(n-1)) goto 60

      do 40 i = 2, n-2
   40    if(s.gt.x(i+1)) goto 50

   50    if(s.ge..5*(x(i-1)+x(i+2))) i = i - 1
         goto 70

   60    i = n - 2
   70    qpol = (s-x(i+1))*(s-x(i+2))*y(i)
     &        / ((x(i)-x(i+1))*(x(i)-x(i+2)))
     &        + (s-x(i))*(s-x(i+2))*y(i+1)
     &        / ((x(i)-x(i+1))*(x(i+2)-x(i+1)))
     &        + (s-x(i))*(s-x(i+1))*y(i+2)
     &        / ((x(i+2)-x(i))*(x(i+2)-x(i+1)))
         return

   80    qpol = y(1)+(s-x(1))*(y(2)-y(1))/(x(2)-x(1))

*-----------------------------------------------------------------------

      return
      end


************************************************************************
*                                                                      *
      function spol(s,x,y,e,u,n,in,id,m1,m2)
*                                                                      *
*       cubic spline interpolation with parabolic runout.              *
*       Last modified by K.Niita on 2009/09/28                         *
*                                                                      *
************************************************************************

      implicit real*8 (a-h,o-z)

*-----------------------------------------------------------------------

      parameter (one=1.d0)
      dimension  x(n),y(n),e(n),u(n)

*-----------------------------------------------------------------------

         if(in.ne.1) goto 30
         in = 2
         n1 = n-1
         e(1) = one
         u(1) = 0.
         b1 = x(2)-x(1)
         c1 = (y(2)-y(1))/b1

      do 10 j = 2, n1
         b2 = x(j+1)-x(j)
         c2 = (y(j+1)-y(j))/b2
         b = x(j+1)-x(j-1)
         d = (c2-c1)/b
         c = b1/b
         b1 = b2
         c1 = c2
         p = c*e(j-1)+one+one
         e(j) = (c-one)/p
   10    u(j) = (d-c*u(j-1))/p
         e(n) = u(n1)/(one-e(n1))

      do 20 kk = 1, n1
         k = n-kk
   20    e(k) = e(k)*e(k+1)+u(k)

         id = 0
         m2 = 0
         m1 = n
         if(x(1).le.x(n)) goto 30
         id = 1
         m2 = n
         m1 = 0
   30    if(s.lt.x(m1+id).and.s.gt.x(m2+1-id)) goto 40
         if(s.ge.x(m1+id)) mu = m1+2*id
         if(s.le.x(m2+1-id)) mu = m2+2*(1-id)
         goto 60

   40    ml = m2
         mu = m1

   50    m3 = (ml+mu)/2
         if(s.lt.x(m3)) mu = m3
         if(s.ge.x(m3)) ml = m3
         if(iabs(mu-ml).gt.1) goto 50
         mu = mu + id

   60    spol = (e(mu-1)*((x(mu)-s)**3)+e(mu)*((s-x(mu-1))**3)
     &        + (y(mu-1)-e(mu-1)*((x(mu)-x(mu-1))**2))*(x(mu)-s)
     &        + (y(mu)-e(mu)*((x(mu)-x(mu-1))**2))*(s-x(mu-1)))
     &        / (x(mu)-x(mu-1))

*-----------------------------------------------------------------------

      return
      end

