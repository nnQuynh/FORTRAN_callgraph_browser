      read(iu) aa
      return

*-----------------------------------------------------------------------
*     fast double precision write                              fastdw
*-----------------------------------------------------------------------

      entry fastdw(iu,aa,n)
      if(n.eq.0) return
      write(iu) aa
      return

*-----------------------------------------------------------------------
*     fast single precision read                               fastsr
*-----------------------------------------------------------------------

      entry fastsr(iu,bb,n)
      if(n.eq.0) return
      read(iu) bb
      return

*-----------------------------------------------------------------------
*     fast single precision write                              fastsw
*-----------------------------------------------------------------------

      entry fastsw(iu,bb,n)
      if(n.eq.0) return
      write(iu) bb
      return

*-----------------------------------------------------------------------
*     fast integer read                                        fastir
*-----------------------------------------------------------------------

      entry fastir(iu,jj,n)
      if(n.eq.0)return
      read(iu)jj
      return

*-----------------------------------------------------------------------
*     fast integer write                                       fastiw
*-----------------------------------------------------------------------

      entry fastiw(iu,jj,n)
      if(n.eq.0) return
      write(iu) jj

*-----------------------------------------------------------------------

      return
      end


