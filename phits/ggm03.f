************************************************************************
*                                                                      *
      subroutine klnishi(e1,e2,cs)
*                                                                      *
*       sample the klein-nishina distribution.                         *
*       e1 = energy in.  e2 = energy out.  cs = scattering cosine.     *
*       the unit of energy is the rest mass of the electron.           *
*       reference: r. n. blomquist and e. m. gelbard, nuclear science  *
*       and engineering, 83, 380-384 (1983)                            *
*       Last modified by K.Niita on 2009/10/06                         *
*                                                                      *
************************************************************************

      implicit double precision (a-h,o-z)

*-----------------------------------------------------------------------

         a = 1./e1
         b = 1./(1.+2.*e1)

*-----------------------------------------------------------------------
*     kahn's method (e < 1.5 mev) aecu-3259
*-----------------------------------------------------------------------

         if(e1.ge.3.) goto 30
         t = 1./(1.+8.*b)

   10    if(rang().le.t) goto 20
         s = (1.+2.*e1*rang())*b
         cs = 1.+a*(1.-1./s)
         if(rang().gt..5*(cs**2+s)) goto 10
         e2 = e1*s
         return

   20    r = 2.*rang()
         s = 1./(1.+e1*r)
         if(rang().gt.4.*s*(1.-s)) goto 10
         e2 = e1*s
         cs = 1.-r
         return

*-----------------------------------------------------------------------
*     koblinger's method (e > 1.5 mev) nse 56,218(1975)
*-----------------------------------------------------------------------

   30    t = rang()*(4.*a+.5*(1.-b**2)-(1.-2.*(1.+e1)*a**2)*log(b))
         if(t.gt.2.*a) goto 40
         r = 2.*rang()
         cs = 1.-r
         e2 = 1./(a+r)
         return

   40    if(t.gt.4.*a) goto 50
         e2 = e1*(1.+rang()*(b-1.))
         cs = 1.+a-1./e2
         return

   50    if(t.gt.4.*a+.5*(1.-b**2)) goto 60
         e2 = e1*sqrt(1.-rang()*(1.-b**2))
         cs = 1.+a-1./e2
         return

   60    e2 = e1*b**rang()
         cs = 1.+a-1./e2

*-----------------------------------------------------------------------

      return
      end

