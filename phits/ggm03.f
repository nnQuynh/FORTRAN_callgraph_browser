*                                                                      *
      function simint(d,f,n)
*                                                                      *
*       integrate a tabular function f(x) from x1 to xn, where f(x) is *
*       given at n equally-spaced abscissae x1...xn. use a simpson rule*
*       dependent on the number of points n.  return the integral.     *
*       d = xn - x1 is the distance between the limits of integration. *
*       Last modified by K.Niita on 2009/09/30                         *
*                                                                      *
************************************************************************

      implicit double precision (a-h,o-z)

*-----------------------------------------------------------------------

      dimension f(n)

*-----------------------------------------------------------------------

      if(n.gt.1) goto 10
      simint = 0.
      return

   10 if(n.gt.2) goto 20
      simint = .5*(f(1)+f(2))*d
      return

   20 if(n.gt.3) goto 30
      simint = (f(1)+4.*f(2)+f(3))*d/6.
      return

   30 if(n.gt.4) goto 40
      simint = .125*(f(1)+3.*(f(2)+f(3))+f(4))*d
      return

   40 if(n.eq.(n/2)*2) goto 70
         s2 = 0.
      do 50 i = 3, n-2, 2
   50    s2 = s2+f(i)
         s4 = 0.
      do 60 i = 2, n-1, 2
   60    s4 = s4+f(i)
         simint = (f(1)+4.*s4+2.*s2+f(n))*d/(3*(n-1))
      return

   70 if(n.gt.6) goto 80
         simint = (f(1)+3.875*(f(2)+f(5))
     &          + 2.625*(f(3)+f(4))+f(6))*d/(3*(n-1))
      return

   80    s2 = 0.
      do 90 i = 6, n-2, 2
   90    s2 = s2+f(i)
         s4 = 0.
      do 100 i = 7, n-1, 2
  100    s4 = s4+f(i)
         simint = (f(1)+3.875*(f(2)+f(5))
     &          + 2.625*(f(3)+f(4))+4.*s4+2.*s2+f(n))*d/(3*(n-1))

*-----------------------------------------------------------------------

      return
      end

