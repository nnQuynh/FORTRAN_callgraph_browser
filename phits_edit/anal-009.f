************************************************************************


*-----------------------------------------------------------------------
*        inelastic frag
*-----------------------------------------------------------------------



*-----------------------------------------------------------------------
*        nucleus
*-----------------------------------------------------------------------

            if( ik .eq. 0 ) then

            end if

*-----------------------------------------------------------------------
*        proton
*-----------------------------------------------------------------------

            if( ik .eq. 1 ) then

                  ekin = ( et - rm ) * 1000.0

                  pl2 = px**2 + py**2 + pz**2

                  if( pl2 .gt. 0.0 ) then

                     cosa = pz / sqrt(pl2)

                     call jfill1(1,ekin,cosa,sdmfac,
     &                           1.0/2.0/pi*qmdfac/sqrt(pl2))

                  end if

            end if

*-----------------------------------------------------------------------
*        pions
*-----------------------------------------------------------------------

            if( ik .eq. 3 .and. ic .eq. -1 ) then

                  ekin = ( et - rm ) * 1000.0

                  pl2 = px**2 + py**2 + pz**2

                  if( pl2 .gt. 0.0 ) then

                     cosa = pz / sqrt(pl2)

                     call jfill1(2,ekin,cosa,sdmfac,
     &                           1.0/2.0/pi*qmdfac/sqrt(pl2))

                  end if

            end if

*-----------------------------------------------------------------------

      return


