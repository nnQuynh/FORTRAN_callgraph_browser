            xmax0 = elab * 1000.0
            xmax1 = xmax0 * 1.3

            dx    = log( xmax0 / xmin ) / dble( ix )
            nx    = nint( log( xmax1 / xmin ) / dx )
            xmax  = xmin + exp( dx * dble( nx ) )

*-----------------------------------------------------------------------

            call jbook1(2,'photon log DDX',
     &                  tfac,ilog,inum,ifac,nx,xmin,xmax,ipx,nw,wi,wt)

*-----------------------------------------------------------------------


      return


