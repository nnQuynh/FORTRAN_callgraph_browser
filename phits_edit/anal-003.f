            xmax1 = xmax0 * 1.3

            dx    = ( xmax0 - xmin ) / dble( ix )
            nx    = nint( ( xmax1 - xmin ) / dx )
            xmax  = xmin + dx * dble( nx )

*-----------------------------------------------------------------------

            call jbook1(1,'photon linear DDX',
     &                  tfac,ilog,inum,ifac,nx,xmin,xmax,ipx,nw,wi,wt)

