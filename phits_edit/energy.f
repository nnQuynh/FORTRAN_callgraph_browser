       subroutine submas(nn,nz,amk)
c ----------------------------------------------------------------------
      implicit real*8 (a-h,o-z)
c
      real*8 idb
      data a1,a2,a3,a4/
     [   -17.08000d+0,  30.13800d+0, -31.32201d+0,  24.19200d+0  /
      data c1,c2,c3,c4/
     [    35.21700d+0, -89.81100d+0,  92.94000d+0,   0.56912d+0  /
c ----------------------------------------------------------------------
c
      idb=dble(nn-nz)
   17 z=dble(nz)
      a=dble(nn+nz)
      da=a
      sz=1.5d0
      ro=1.13d0
      ac=0.864d+0/ro
      sr=dsqrt(da**2/4.d0+(sz/ro)**6/27.d0)
      rzero=(da/2.d0+sr)**0.33333333333333d0-(sr-da/2.d0)**0.33333333333
     1 333d0
      if(dabs(rzero).lt.1.d-30) go to 1500
      zr=sz/(ro*rzero)
      go to 1600
 1500 write(6,1550) rzero, a, z
      ec=0.d+0
      go to 1700
 1550 format(//10x,'rzero = ',1pe15.4, 5x,'a = ',e15.4,2x,'z = ',e15.4)
 1600 ec=ac*z**2/a**2*rzero**5*(1.0d+0+5.0d+0/6.0d+0*zr**2+0.5d+0*zr**3+
     &   1.0d+0/6.0d+0*zr**4-1.0d+0/42.0d+0*zr**5)-0.66d+0/ro*(z/a)**
     &   1.333333333333d+0*a
 1700 continue
      x=1.0d+0/a**0.3333333333d+0
      xx=x**2
      xxx=1.0d+0/a
      ai=a1+a2*x+a3*xx+a4*xxx
      bi=15.0d+0*xx
      ci=c1+c2*x+c3*xx/(1.0d+0+c4*x)
      aie=ai*a
      bie=bi*dabs(idb)
      cie=ci*idb**2/a
c     total mass excess
      amk=7.68023d+0*a+0.39120d+0*idb+aie+bie+cie+ec-14.33d-6*z**2.39
c     odd-odd term
      eoo=0.d+0
      mp=1
      if((nz/2)*2.eq.nz) mp=0
      if((nn/2)*2.eq.nn) mp=0
      if(mp.eq.0) go to 10
      eoo=-(11719.21d+0/(a+31.4113d+0)**2-1.321495d+6/(a+48.1170d+0)**3)
      amk=amk+eoo
   10 return
      end


