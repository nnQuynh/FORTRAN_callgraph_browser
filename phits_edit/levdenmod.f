      function a(ia,iz,u)
*
*     Ignatyuk level density parameter
*
*     variable       IN/OUT
*     ia             I       mass number
*     iz             I       charge number
*     u              I       excitation energy of nuclei

*     a_levden_param O       Level density parameter (/MeV)
************************************************************************
      implicit doubleprecision(a-h,o-z)

      a = ainf(inuc1(ia,ia-iz)) * (1.d0 + dW(inuc1(ia,ia-iz))
     & / u * (1.d0 - exp( -1.d0 * gamma(inuc1(ia,ia-iz)) * u )  ) )

      if( a .eq. 0.d0) a = getag(u, iz, ia - iz, isdum)

      return
      end function


C--------------------------------------------------------------------
      function rho_levden(ia,iz,u,sp,nv)
C
C     variable       IN/OUT
C     ia             I       mass number
C     iz             I       charge number
C     u              I       excitation energy of nuclei (MeV)
C     sp             I       spin. If sp = -1.d0, level integrated over all J
C     nv             I       level density version number
C                            1:old GEM based on GC model. 2:RIPL based GC model

C     rho_levden     O       Level density (/MeV)
C--------------------------------------------------------------------
      implicit doubleprecision(a-h,o-z)

      include 'err.inc'

      IF(u .lt. 1.d-10) then
       rho_levden = 1.d-10
       return
      endif

         nn = ia - iz

      if(nv .eq. 1 .or. inuc1(ia,ia-iz) .ne. 0 .or. iz .gt. maxpt .or.
     &   ia-iz .gt. maxnt ) then  ! nv = 1 or structure parameter missing

         ux     = 2.5d0 + 150.d0 / dble(ia)
         delta  = paire(iz,ia-iz)
         ex     = ux + delta

         if( u .ge. ex ) then
            smalla = getag(u,iz,ia-iz,isdum)
            eag =  2.d0 * sqrt( smalla * ( u - delta ) )
            rho = exp( eag )
     &       / smalla**.25d0 / ( u - delta )**1.25d0
         else
            ax  = getag(ex,iz,nn,isdum)
            tau = 1.0 / ( sqrt( ax / ux ) - 1.5d0 / ux )
            eag = 2.d0 * sqrt( ax * ux ) - ( ex - u ) / tau
            rho = exp( eag ) / ax**.25d0 / ux**1.25d0
         end if

      else ! RIPL based

         ux     = Ematch(inuc1(ia,ia-iz))
         smalla = a(ia,iz,u)
         delta  = pairing(inuc1(ia,ia-iz))
         ex     = ux + delta
         tau    = T(inuc1(ia,ia-iz))

         if( u .ge. ex ) then
            eag =  2.d0 * sqrt( smalla * ( u - delta ) )
            rho = exp( eag )
     &       / smalla**.25d0 / ( u - delta )**1.25d0
         else
            eag = 2.d0 * sqrt( smalla * ux ) - ( ex - u ) / tau
            rho = exp( eag ) / smalla**.25d0 / ux**1.25d0
         end if

      endif


c  if spin is known, rho is level at the spin.
      if(sp .ge. 0) then
         s = 0.146d0 * sqrt(a(ia,iz,u) * u) * dble(ia)** 0.666666d0 ! spin cut-off parameter
         rho = exp( - sp*(sp+1.d0)/ (2.d0 * s) )
     & *(2.d0 * sp + 1.d0) / 24.d0 / sqrt(2.d0) / sqrt(s)**3 * rho
      endif


      rho_levden = rho

      return
      end function


************************************************************************
*
      function constT(iz,in)
*
*     Ignatyuk level density parameter
*
*     variable       IN/OUT
*     ia             I       mass number
*     iz             I       charge number
*     u              I       excitation energy of nuclei

*     a_levden_param O       Level density parameter (/MeV)
************************************************************************
      implicit doubleprecision(a-h,o-z)

      if(inuc1(iz, in) .ne. 0) then
        constT = T(inuc1(iz, in))
      else ! Gilbert Cameron systematics taken from NIM B, 171, 251-258 (2000)
        ux     = 2.5d0 + 150.d0/dble(iz+in)
        constT = ( sqrt( dble(iz+in) / 8.d0 / ux) - 1.5d0 / ux ) ** -1
      endif

      return
      end function

